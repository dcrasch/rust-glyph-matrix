//! Nothing Phone (2) Glyph LED controller — egui front-end.
//!
//! On Android the app calls into the Nothing Glyph SDK via JNI.
//! On desktop it displays the same UI without touching any LEDs (useful for
//! layout iteration without deploying to the phone).

pub use eframe;

use std::collections::VecDeque;
use std::time::{Duration, Instant};

use eframe::egui::{self, Color32, Image, RichText, Slider};

/// Time each glyph stays lit in demo mode.
const DEMO_STEP: Duration = Duration::from_millis(500);

/// Marks mask pixels that belong to no glyph.
const NO_GLYPH: u8 = u8::MAX;

/// Touch slop in mask pixels. Each empty pixel joins the nearest glyph within this distance.
const HIT_RADIUS: u32 = 40;

/// Number of glyphIds on the Nothing Phone (2), from the glyphId table.
pub const GLYPH_COUNT: usize = 11;

/// Labels in glyphId order. Index i is glyphId i + 1.
const GLYPH_LABELS: [&str; GLYPH_COUNT] = [
    "1  Camera top",
    "2  Camera bottom",
    "3  Diagonal",
    "4  Battery top right (4.1–4.16)",
    "5  Battery top left",
    "6  Battery top vertical (left)",
    "7  Battery bottom left",
    "8  Battery bottom right",
    "9  Battery bottom vertical (right)",
    "10  USB line (10.1–10.8)",
    "11  USB dot",
];

/// Space gray phone body, matching the body rect in scripts/render_phone_back.py.
const PHONE_BODY: Color32 = Color32::from_rgb(0x53, 0x51, 0x50);

/// Lit overlay per glyphId (white on transparent), generated by scripts/render_phone_back.py.
const GLYPH_PNGS: [&[u8]; GLYPH_COUNT] = [
    include_bytes!("../assets/glyph_1.png"),
    include_bytes!("../assets/glyph_2.png"),
    include_bytes!("../assets/glyph_3.png"),
    include_bytes!("../assets/glyph_4.png"),
    include_bytes!("../assets/glyph_5.png"),
    include_bytes!("../assets/glyph_6.png"),
    include_bytes!("../assets/glyph_7.png"),
    include_bytes!("../assets/glyph_8.png"),
    include_bytes!("../assets/glyph_9.png"),
    include_bytes!("../assets/glyph_10.png"),
    include_bytes!("../assets/glyph_11.png"),
];

fn glyph_source(i: usize) -> egui::ImageSource<'static> {
    match i {
        0 => egui::include_image!("../assets/glyph_1.png"),
        1 => egui::include_image!("../assets/glyph_2.png"),
        2 => egui::include_image!("../assets/glyph_3.png"),
        3 => egui::include_image!("../assets/glyph_4.png"),
        4 => egui::include_image!("../assets/glyph_5.png"),
        5 => egui::include_image!("../assets/glyph_6.png"),
        6 => egui::include_image!("../assets/glyph_7.png"),
        7 => egui::include_image!("../assets/glyph_8.png"),
        8 => egui::include_image!("../assets/glyph_9.png"),
        9 => egui::include_image!("../assets/glyph_10.png"),
        _ => egui::include_image!("../assets/glyph_11.png"),
    }
}

pub struct GlyphApp {
    /// Which glyphs are currently switched on, indexed by glyphId - 1.
    glyphs: [bool; GLYPH_COUNT],
    /// Progress value shown on the D1 / C1 strip (0–100).
    progress: i32,
    /// Whether the breathing animation is active.
    animate: bool,
    /// Status line shown at the bottom of the UI.
    status: String,
    /// Glyph index for every mask pixel (NO_GLYPH if none), used for click hit-testing.
    hit_map: Vec<u8>,
    /// Width and height of hit_map.
    hit_size: [usize; 2],
    /// Whether demo mode is stepping through the glyphs.
    demo: bool,
    /// Glyph currently lit by demo mode.
    demo_index: usize,
    /// When demo_index was last changed.
    demo_since: Instant,
    /// Platform-specific Glyph handle (None on desktop).
    #[cfg(target_os = "android")]
    glyph: glyph::GlyphHandle,
}

impl GlyphApp {
    pub fn new(cc: &eframe::CreationContext<'_>) -> Self {
        egui_extras::install_image_loaders(&cc.egui_ctx);

        #[cfg(target_os = "android")]
        let glyph = glyph::GlyphHandle::init();

        let masks: Vec<egui::ColorImage> = GLYPH_PNGS
            .iter()
            .map(|bytes| egui_extras::image::load_image_bytes(bytes).expect("glyph mask"))
            .collect();
        let hit_size = masks[0].size;
        let hit_map = build_hit_map(&masks);

        let demo = std::env::var_os("GLYPH_DEMO").is_some();

        Self {
            glyphs: [false; GLYPH_COUNT],
            progress: 0,
            animate: false,
            status: "Ready".into(),
            hit_map,
            hit_size,
            demo,
            demo_index: 0,
            demo_since: Instant::now(),
            #[cfg(target_os = "android")]
            glyph,
        }
    }

    /// Returns the glyph index under `pos`, using the expanded hit map.
    fn glyph_at(&self, rect: egui::Rect, pos: egui::Pos2) -> Option<usize> {
        if !rect.contains(pos) {
            return None;
        }
        let [w, h] = self.hit_size;
        let u = (pos.x - rect.min.x) / rect.width();
        let v = (pos.y - rect.min.y) / rect.height();
        let x = ((u * w as f32) as usize).min(w - 1);
        let y = ((v * h as f32) as usize).min(h - 1);
        match self.hit_map[y * w + x] {
            NO_GLYPH => None,
            i => Some(i as usize),
        }
    }

    /// Lights only `index` and sends it to the Glyph.
    fn demo_show(&mut self, index: usize) {
        self.demo_index = index;
        self.demo_since = Instant::now();
        self.glyphs = [false; GLYPH_COUNT];
        self.glyphs[index] = true;
        self.apply();
    }

    fn apply(&mut self) {
        #[cfg(target_os = "android")]
        {
            let result = if self.animate {
                self.glyph.animate(&self.glyphs)
            } else {
                self.glyph.toggle(&self.glyphs)
            };
            self.status = match result {
                Ok(()) => "OK".into(),
                Err(e) => format!("Error: {e}"),
            };
        }
        #[cfg(not(target_os = "android"))]
        {
            self.status = format!(
                "Desktop: glyphs {:?} animate={}",
                self.glyphs, self.animate
            );
        }
    }

    fn apply_progress(&mut self) {
        #[cfg(target_os = "android")]
        {
            let result = self.glyph.set_progress(&self.glyphs, self.progress);
            self.status = match result {
                Ok(()) => format!("Progress {}%", self.progress),
                Err(e) => format!("Error: {e}"),
            };
        }
        #[cfg(not(target_os = "android"))]
        {
            self.status = format!("Desktop: progress {}%", self.progress);
        }
    }

    fn turn_off(&mut self) {
        self.glyphs = [false; GLYPH_COUNT];
        self.animate = false;

        #[cfg(target_os = "android")]
        {
            let result = self.glyph.turn_off();
            self.status = match result {
                Ok(()) => "All off".into(),
                Err(e) => format!("Error: {e}"),
            };
        }
        #[cfg(not(target_os = "android"))]
        {
            self.status = "Desktop: all off".into();
        }
    }
}

/// Assigns every mask pixel to a glyph. Opaque pixels keep their glyph (first in glyphId order wins),
/// and empty pixels take the glyph of the nearest opaque pixel within HIT_RADIUS.
fn build_hit_map(masks: &[egui::ColorImage]) -> Vec<u8> {
    let [w, h] = masks[0].size;
    let mut map = vec![NO_GLYPH; w * h];
    let mut dist = vec![u32::MAX; w * h];
    let mut queue = VecDeque::new();

    for (i, mask) in masks.iter().enumerate() {
        for (p, px) in mask.pixels.iter().enumerate() {
            if map[p] == NO_GLYPH && px.a() > 0 {
                map[p] = i as u8;
                dist[p] = 0;
                queue.push_back(p);
            }
        }
    }

    while let Some(p) = queue.pop_front() {
        if dist[p] >= HIT_RADIUS {
            continue;
        }
        let (x, y) = (p % w, p / w);
        let neighbors = [
            (x > 0).then(|| p - 1),
            (x + 1 < w).then(|| p + 1),
            (y > 0).then(|| p - w),
            (y + 1 < h).then(|| p + w),
        ];
        for q in neighbors.into_iter().flatten() {
            if dist[q] == u32::MAX {
                dist[q] = dist[p] + 1;
                map[q] = map[p];
                queue.push_back(q);
            }
        }
    }

    map
}

impl eframe::App for GlyphApp {
    fn ui(&mut self, ui: &mut egui::Ui, _frame: &mut eframe::Frame) {
        if self.demo {
            if self.demo_since.elapsed() >= DEMO_STEP {
                self.demo_show((self.demo_index + 1) % GLYPH_COUNT);
            }
            ui.ctx().request_repaint_after(DEMO_STEP);
        }

        egui::CentralPanel::default().show(ui, |ui| {
            ui.heading(RichText::new("Nothing Phone (2)  •  Glyph Control").size(22.0));
            ui.add_space(12.0);

            let phone_height = (ui.available_height() - 260.0).clamp(300.0, 900.0);
            let phone_size = egui::vec2(phone_height * 182.0 / 382.0, phone_height);
            let mut hovered = None;
            ui.vertical_centered(|ui| {
                let (rect, response) = ui.allocate_exact_size(phone_size, egui::Sense::click());
                ui.painter().rect_filled(rect, 44.0 * rect.width() / 182.0, PHONE_BODY);
                Image::new(egui::include_image!("../assets/phone_back.svg")).paint_at(ui, rect);
                for (i, &on) in self.glyphs.iter().enumerate() {
                    if on {
                        Image::new(glyph_source(i)).paint_at(ui, rect);
                    }
                }

                hovered = response.hover_pos().and_then(|pos| self.glyph_at(rect, pos));
                let clicked_glyph = response
                    .interact_pointer_pos()
                    .filter(|_| response.clicked())
                    .and_then(|pos| self.glyph_at(rect, pos));
                if let Some(i) = clicked_glyph {
                    if self.demo {
                        self.demo = false;
                        self.glyphs = [false; GLYPH_COUNT];
                    }
                    self.glyphs[i] = !self.glyphs[i];
                    self.apply();
                }
            });
            let label = if self.demo {
                GLYPH_LABELS[self.demo_index]
            } else {
                hovered.map_or("", |i| GLYPH_LABELS[i])
            };
            ui.label(label);

            ui.add_space(10.0);
            ui.separator();
            ui.add_space(6.0);

            ui.horizontal(|ui| {
                ui.label("Progress (4.1–4.16 ring / 10.1–10.8 strip):");
                if ui
                    .add(Slider::new(&mut self.progress, 0..=100).suffix("%"))
                    .changed()
                {
                    self.apply_progress();
                }
            });

            ui.add_space(6.0);
            ui.checkbox(&mut self.animate, "Breathing animation");

            ui.add_space(6.0);
            if ui.checkbox(&mut self.demo, "Demo mode").changed() {
                if self.demo {
                    self.demo_show(0);
                } else {
                    self.turn_off();
                }
            }

            ui.add_space(10.0);
            ui.horizontal(|ui| {
                if ui
                    .button(RichText::new("All Off").size(18.0).color(Color32::RED))
                    .clicked()
                {
                    self.turn_off();
                }
            });

            ui.add_space(12.0);
            ui.separator();
            ui.label(RichText::new(&self.status).color(Color32::LIGHT_BLUE));
        });
    }
}

// ---------------------------------------------------------------------------
// Desktop entry point
// ---------------------------------------------------------------------------

#[cfg(not(target_os = "android"))]
pub fn run() -> eframe::Result {
    eframe::run_native(
        "Glyph Control",
        eframe::NativeOptions {
            viewport: egui::ViewportBuilder::default()
                .with_inner_size([520.0, 980.0])
                .with_title("Glyph Control"),
            renderer: eframe::Renderer::Glow,
            ..Default::default()
        },
        Box::new(|cc| Ok(Box::new(GlyphApp::new(cc)))),
    )
}

// ---------------------------------------------------------------------------
// Android entry point
// ---------------------------------------------------------------------------

#[cfg(target_os = "android")]
#[unsafe(no_mangle)]
pub fn android_main(app: winit::platform::android::activity::AndroidApp) {
    android_logger::init_once(
        android_logger::Config::default()
            .with_max_level(log::LevelFilter::Info)
            .with_tag("rust-glyph-matrix"),
    );

    let mut options = eframe::NativeOptions {
        renderer: eframe::Renderer::Glow,
        ..Default::default()
    };
    options.android_app = Some(app);

    if let Err(err) = eframe::run_native(
        "Glyph Control",
        options,
        Box::new(|cc| Ok(Box::new(GlyphApp::new(cc)))),
    ) {
        log::error!("eframe error: {err}");
    }
}

// ---------------------------------------------------------------------------
// Android Glyph JNI bridge
// ---------------------------------------------------------------------------

#[cfg(target_os = "android")]
mod glyph {
    use jni::objects::{JObject, JValue};
    use jni::refs::Global;
    use ndk_context::android_context;

    use super::GLYPH_COUNT;

    pub struct GlyphHandle {
        bridge: Global<JObject<'static>>,
    }

    // SAFETY: the Global reference is valid across threads; JNI access is
    // serialized by attaching each calling thread before use.
    unsafe impl Send for GlyphHandle {}
    unsafe impl Sync for GlyphHandle {}

    impl GlyphHandle {
        pub fn init() -> Self {
            let ctx = android_context();
            // SAFETY: the JavaVM pointer is valid for the lifetime of the process.
            let vm = unsafe { jni::JavaVM::from_raw(ctx.vm().cast()) };
            let bridge_ref = vm
                .attach_current_thread(|env| {
                    let activity =
                        unsafe { JObject::from_raw(env, ctx.context().cast()) };

                    // Load our classes.dex (containing GlyphBridge + Glyph SDK)
                    // via DexClassLoader, then call GlyphBridge.init via
                    // reflection so the class is resolved from our loader.
                    let bridge = load_dex_and_init_bridge(env, &activity)?;
                    env.new_global_ref(bridge)
                })
                .expect("GlyphBridge.init failed");

            Self { bridge: bridge_ref }
        }

        pub fn toggle(&self, glyphs: &[bool; GLYPH_COUNT]) -> Result<(), String> {
            let mask = glyphs_to_mask(glyphs);
            self.call_int_void(jni::jni_str!("toggle"), mask)
        }

        pub fn animate(&self, glyphs: &[bool; GLYPH_COUNT]) -> Result<(), String> {
            let mask = glyphs_to_mask(glyphs);
            self.call_int_void(jni::jni_str!("animate"), mask)
        }

        pub fn set_progress(&self, glyphs: &[bool; GLYPH_COUNT], progress: i32) -> Result<(), String> {
            let mask = glyphs_to_mask(glyphs);
            self.with_vm(|env| {
                env.call_method(
                    self.bridge.as_obj(),
                    jni::jni_str!("setProgress"),
                    jni::jni_sig!((int, int) -> void),
                    &[JValue::Int(mask), JValue::Int(progress)],
                )?;
                Ok(())
            })
        }

        pub fn turn_off(&self) -> Result<(), String> {
            self.with_vm(|env| {
                env.call_method(
                    self.bridge.as_obj(),
                    jni::jni_str!("turnOff"),
                    jni::jni_sig!(() -> void),
                    &[],
                )?;
                Ok(())
            })
        }

        fn call_int_void(
            &self,
            name: &jni::strings::JNIStr,
            arg: i32,
        ) -> Result<(), String> {
            self.with_vm(|env| {
                env.call_method(
                    self.bridge.as_obj(),
                    name,
                    jni::jni_sig!((int) -> void),
                    &[JValue::Int(arg)],
                )?;
                Ok(())
            })
        }

        fn with_vm<F>(&self, f: F) -> Result<(), String>
        where
            F: for<'e> FnOnce(&mut jni::Env<'e>) -> Result<(), jni::errors::Error>,
        {
            let ctx = android_context();
            let vm = unsafe { jni::JavaVM::from_raw(ctx.vm().cast()) };
            vm.attach_current_thread(f).map_err(|e| e.to_string())
        }
    }

    impl Drop for GlyphHandle {
        fn drop(&mut self) {
            let _ = self.with_vm(|env| {
                env.call_method(
                    self.bridge.as_obj(),
                    jni::jni_str!("destroy"),
                    jni::jni_sig!(() -> void),
                    &[],
                )?;
                Ok(())
            });
        }
    }

    /// Loads `classes.dex` from the app's own APK via `DexClassLoader`, then
    /// calls `GlyphBridge.init(context)` via reflection so the class is
    /// resolved through our custom loader (not the system class loader, which
    /// does not include our dex because NativeActivity sets hasCode=false).
    fn load_dex_and_init_bridge<'e>(
        env: &mut jni::Env<'e>,
        context: &JObject<'_>,
    ) -> Result<JObject<'e>, jni::errors::Error> {
        // context.getPackageCodePath() → "/data/app/.../base.apk"
        let apk_path = env
            .call_method(
                context,
                jni::jni_str!("getPackageCodePath"),
                jni::jni_sig!(() -> java.lang.String),
                &[],
            )?
            .l()?;

        // context.getCacheDir().getAbsolutePath() → writable dex opt dir
        let cache_dir_file = env
            .call_method(
                context,
                jni::jni_str!("getCacheDir"),
                jni::jni_sig!(() -> java.io.File),
                &[],
            )?
            .l()?;
        let cache_path = env
            .call_method(
                &cache_dir_file,
                jni::jni_str!("getAbsolutePath"),
                jni::jni_sig!(() -> java.lang.String),
                &[],
            )?
            .l()?;

        // parent = context.getClassLoader()
        let parent_loader = env
            .call_method(
                context,
                jni::jni_str!("getClassLoader"),
                jni::jni_sig!(() -> java.lang.ClassLoader),
                &[],
            )?
            .l()?;

        // new DexClassLoader(apkPath, cacheDir, null, parent)
        let dcl_cls = env.find_class(jni::jni_str!("dalvik/system/DexClassLoader"))?;
        let null = JObject::null();
        let loader = env.new_object(
            &dcl_cls,
            jni::jni_sig!(
                (java.lang.String, java.lang.String, java.lang.String, java.lang.ClassLoader)
            ),
            &[
                JValue::Object(&apk_path),
                JValue::Object(&cache_path),
                JValue::Object(&null),
                JValue::Object(&parent_loader),
            ],
        )?;
        log::info!("DexClassLoader created from APK");

        // loader.loadClass("dev.rustglyphmatrix.GlyphBridge")
        let class_name = env.new_string("dev.rustglyphmatrix.GlyphBridge")?;
        let bridge_cls = env
            .call_method(
                &loader,
                jni::jni_str!("loadClass"),
                jni::jni_sig!((java.lang.String) -> java.lang.Class),
                &[JValue::Object(&class_name)],
            )?
            .l()?;
        log::info!("GlyphBridge class loaded");

        // Use reflection: bridge_cls.getMethod("init", Context.class).invoke(null, context)
        // Easier: call the static method via env using the loaded class object as JClass.
        // JNI lets us call static methods on a jclass obtained from loadClass.
        // SAFETY: bridge_cls is a java.lang.Class object returned by loadClass.
        let bridge_jclass: jni::objects::JClass<'_> = unsafe {
            jni::objects::JClass::from_raw(env, bridge_cls.as_raw())
        };
        let bridge = env
            .call_static_method(
                &bridge_jclass,
                jni::jni_str!("init"),
                jni::jni_sig!(
                    type_map = { GlyphBridge => "dev.rustglyphmatrix.GlyphBridge" },
                    (android.content.Context) -> GlyphBridge
                ),
                &[JValue::Object(context)],
            )?
            .l()?;
        log::info!("GlyphBridge.init succeeded");
        Ok(bridge)
    }

    /// Packs the glyph flags into a bitmask: bit i is glyphId i + 1.
    fn glyphs_to_mask(glyphs: &[bool; GLYPH_COUNT]) -> i32 {
        let mut mask: i32 = 0;
        for (i, &on) in glyphs.iter().enumerate() {
            if on {
                mask |= 1 << i;
            }
        }
        mask
    }
}
